/*
 * Deep merge.
 *
 * English is always the complete base structure.
 * Every other language overrides only the keys
 * that have an explicit translation.
 *
 * Missing keys safely fall back to English.
 */
function mergeTranslations(base, override) {
  if (!override || typeof override !== "object") {
    return base;
  }

  const result = {
    ...base,
  };

  Object.keys(override).forEach((key) => {
    const baseValue = result[key];
    const overrideValue = override[key];

    if (
      baseValue &&
      typeof baseValue === "object" &&
      !Array.isArray(baseValue) &&
      overrideValue &&
      typeof overrideValue === "object" &&
      !Array.isArray(overrideValue)
    ) {
      result[key] = mergeTranslations(
        baseValue,
        overrideValue
      );
    } else {
      result[key] = overrideValue;
    }
  });

  return result;
}

